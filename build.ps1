$ErrorActionPreference = 'Stop'
Set-Location -LiteralPath $PSScriptRoot
# Windows PowerShell 5.1 reads a BOM-less .ps1 as ANSI, which silently corrupts the
# Chinese literals these scripts rely on. Fail loudly instead of misbehaving later.
foreach ($script in Get-ChildItem -LiteralPath $PSScriptRoot -Filter '*.ps1') {
    $bytes = [System.IO.File]::ReadAllBytes($script.FullName)
    if ($bytes.Length -lt 3 -or $bytes[0] -ne 0xEF -or $bytes[1] -ne 0xBB -or $bytes[2] -ne 0xBF) {
        throw "$($script.Name) 缺少 UTF-8 BOM，Windows PowerShell 5.1 会误读其中的中文。请以「UTF-8 带 BOM」重新保存。"
    }
}
. "$PSScriptRoot\version.ps1"
$compiler = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
$sdk = Join-Path $PSScriptRoot 'vendor\webview2'
if (-not (Test-Path -LiteralPath (Join-Path $sdk 'lib\net462\Microsoft.Web.WebView2.Core.dll'))) {
    throw 'Missing WebView2 SDK. Extract Microsoft.Web.WebView2 1.0.2903.40 into vendor\webview2 first. See README.md.'
}
New-Item -ItemType Directory -Path 'dist','artifacts','artifacts\build' -Force | Out-Null
# VERSION is the single source of truth, so the version reaches C# through a generated file.
# 必须写入 AssemblyFileVersion：否则 exe 属性里的版本是 0.0.0.0，出问题时无法确认用户装的是哪一版。
$generated = Join-Path $PSScriptRoot 'artifacts\build\Version.g.cs'
$generatedCode = @"
// Generated by build.ps1 from VERSION. Do not edit.
using System.Reflection;

[assembly: AssemblyVersion("$AppVersion4")]
[assembly: AssemblyFileVersion("$AppVersion4")]
[assembly: AssemblyInformationalVersion("$AppVersion")]
[assembly: AssemblyTitle("校园网一键连接")]
[assembly: AssemblyProduct("校园网一键连接")]
[assembly: AssemblyDescription("连接校园网 Wi-Fi 并自动完成深澜 SRun 认证")]

namespace CampusConnect
{
    internal static class BuildInfo
    {
        internal const string Version = "$AppVersion";
    }
}
"@
[System.IO.File]::WriteAllText($generated, $generatedCode, (New-Object System.Text.UTF8Encoding($true)))
$references = @(
    '/r:System.dll', '/r:System.Core.dll', '/r:System.Drawing.dll', '/r:System.Windows.Forms.dll',
    '/r:System.Security.dll', '/r:System.Runtime.Serialization.dll', '/r:System.Net.Http.dll',
    "/r:$sdk\lib\net462\Microsoft.Web.WebView2.Core.dll",
    "/r:$sdk\lib\net462\Microsoft.Web.WebView2.WinForms.dll"
)
$sources = @(Get-ChildItem -LiteralPath 'src' -Filter '*.cs' | ForEach-Object FullName) + $generated
$common = @('/nologo','/utf8output','/optimize+','/platform:x64','/target:winexe','/resource:src\portal.js,CampusConnect.portal.js','/resource:assets\app-icon.png,CampusConnect.app-icon.png','/win32manifest:src\app.manifest') + $references
foreach ($asset in (Get-ChildItem -LiteralPath 'assets\icons' -Filter '*.path')) { $common += "/resource:$($asset.FullName),CampusConnect.icons.$($asset.Name)" }
Copy-Item -LiteralPath "$sdk\lib\net462\Microsoft.Web.WebView2.Core.dll" -Destination 'dist'
Copy-Item -LiteralPath "$sdk\lib\net462\Microsoft.Web.WebView2.WinForms.dll" -Destination 'dist'
Copy-Item -LiteralPath "$sdk\runtimes\win-x64\native\WebView2Loader.dll" -Destination 'dist'
Copy-Item -LiteralPath "$sdk\LICENSE.txt" -Destination 'dist\WebView2-LICENSE.txt'
& $compiler @common '/out:dist\CampusConnect.exe' @sources
if ($LASTEXITCODE -ne 0) { throw 'Application compile failed.' }
# Icon generation uses System.Drawing only, and does not display a window.
$iconProcess = Start-Process -FilePath (Join-Path $PSScriptRoot 'dist\CampusConnect.exe') -ArgumentList '--make-icon' -Wait -PassThru -WindowStyle Hidden
if ($iconProcess.ExitCode -ne 0) { throw 'Application icon generation failed.' }
& $compiler @common '/win32icon:dist\campus.ico' '/out:dist\CampusConnect.exe' @sources
if ($LASTEXITCODE -ne 0) { throw 'Application compile failed.' }
& $compiler '/nologo' '/utf8output' '/target:exe' '/platform:x64' '/out:dist\CoreTests.exe' '/r:dist\CampusConnect.exe' @references 'tests\CoreTests.cs'
if ($LASTEXITCODE -ne 0) { throw 'Core tests compile failed.' }
& '.\dist\CoreTests.exe'
if ($LASTEXITCODE -ne 0) { throw 'Core tests failed.' }
& $compiler '/nologo' '/utf8output' '/target:exe' '/platform:x64' '/out:dist\RenderingTests.exe' '/r:dist\CampusConnect.exe' @references 'tests\RenderingTests.cs'
if ($LASTEXITCODE -ne 0) { throw 'Rendering tests compile failed.' }
& '.\dist\RenderingTests.exe'
if ($LASTEXITCODE -ne 0) { throw 'Rendering tests failed.' }
& $compiler '/nologo' '/utf8output' '/target:winexe' '/platform:x64' '/out:dist\BrowserTests.exe' '/r:dist\CampusConnect.exe' @references 'tests\BrowserTests.cs'
if ($LASTEXITCODE -ne 0) { throw 'Browser tests compile failed.' }
& $compiler '/nologo' '/utf8output' '/target:exe' '/platform:x64' '/out:dist\ActivationTests.exe' 'tests\ActivationTests.cs'
if ($LASTEXITCODE -ne 0) { throw 'Activation tests compile failed.' }
Copy-Item -LiteralPath '使用说明.txt' -Destination 'dist'
Copy-Item -LiteralPath 'ICON-SOURCES.md' -Destination 'dist'
Copy-Item -LiteralPath 'THIRD-PARTY-NOTICES.md' -Destination 'dist'
Write-Output "Build and core tests complete (version $AppVersion). Run verify-ui.ps1 for browser integration and visual QA."
